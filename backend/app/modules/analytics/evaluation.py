"""Detection evaluation against the Phase 3 ground truth (docs/06 section 8).

Ground truth lives in ``data/generated/<mode>/ground_truth/`` and is never loaded into the
database. It is read here only *after* detection has finished, and only if the generator
manifest proves it belongs to the loaded dataset (same mode, seed and config hash).
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

from app.modules.analytics.detection import Finding

EVALUATED_TYPES = (
    "ALLOCATION_EXCEEDS_AVAILABILITY",
    "EXPIRED_SKILL_TREATED_AS_CURRENT",
    "DUPLICATE_DEMAND",
    "OVERLAPPING_ALLOCATION_CONFLICT",
)
MATCH_KEYS = ("mode", "seed", "config_sha256")


class GroundTruthSource:
    def __init__(self, generated_root: Path) -> None:
        self._root = generated_root

    def load(self, dataset: Mapping[str, str]) -> tuple[dict[str, set[str]] | None, str]:
        """Labelled evaluation keys per anomaly type, or ``None`` and the reason."""
        mode = dataset.get("mode")
        if not mode:
            return None, "the database has no dataset metadata (not generated by datagen)"
        folder = self._root / mode
        manifest_file = folder / "manifest.json"
        truth_file = folder / "ground_truth" / "ground_truth.csv"
        if not manifest_file.is_file() or not truth_file.is_file():
            return None, f"ground truth files not found under {folder}"
        manifest = json.loads(manifest_file.read_text(encoding="utf-8")).get("dataset", {})
        mismatched = [k for k in MATCH_KEYS if str(manifest.get(k)) != str(dataset.get(k))]
        if mismatched:
            return None, f"ground truth does not match the loaded dataset ({', '.join(mismatched)})"
        labels: dict[str, set[str]] = defaultdict(set)
        with truth_file.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle):
                labels[row["anomaly_type"]].add(row["evaluation_key"])
        return dict(labels), truth_file.relative_to(self._root.parent).as_posix()


def _scores(tp: int, fp: int, fn: int) -> dict[str, float | None]:
    precision = tp / (tp + fp) if tp + fp else None
    recall = tp / (tp + fn) if tp + fn else None
    f1 = (
        2 * precision * recall / (precision + recall)
        if precision is not None and recall is not None and precision + recall > 0
        else None
    )
    return {
        "precision": None if precision is None else round(precision, 4),
        "recall": None if recall is None else round(recall, 4),
        "f1": None if f1 is None else round(f1, 4),
    }


def evaluate_detection(
    findings: Iterable[Finding],
    populations: Mapping[str, int],
    labels: Mapping[str, set[str]],
) -> dict[str, Any]:
    detected: dict[str, set[str]] = defaultdict(set)
    for f in findings:
        detected[f.anomaly_type.value].add(f.evaluation_key)
    per_type: dict[str, Any] = {}
    totals = {"tp": 0, "fp": 0, "fn": 0}
    for kind in EVALUATED_TYPES:
        found, truth = detected.get(kind, set()), labels.get(kind, set())
        tp, fp, fn = len(found & truth), len(found - truth), len(truth - found)
        tn = max(0, populations.get(kind, 0) - tp - fp - fn)
        per_type[kind] = {"tp": tp, "fp": fp, "fn": fn, "tn": tn, **_scores(tp, fp, fn)}
        totals["tp"] += tp
        totals["fp"] += fp
        totals["fn"] += fn
    return {
        "available": True,
        "per_type": per_type,
        "micro": {**totals, **_scores(totals["tp"], totals["fp"], totals["fn"])},
    }
