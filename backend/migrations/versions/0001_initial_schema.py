_SCHEDULE_OVERLAP_SQLITE = """
CREATE TRIGGER trg_availability_schedule_no_overlap_{event}
BEFORE {event_sql} ON availability
WHEN NEW.availability_type = 'WORK_SCHEDULE' AND NEW.status <> 'CANCELLED'
BEGIN
    SELECT RAISE(ABORT, 'overlapping WORK_SCHEDULE rows for one employee (BR-VAL-009)')
    WHERE EXISTS (
        SELECT 1 FROM availability AS a
        WHERE a.employee_id = NEW.employee_id
          AND a.availability_id <> NEW.availability_id
          AND a.availability_type = 'WORK_SCHEDULE'
          AND a.status <> 'CANCELLED'
          AND a.start_date <= COALESCE(NEW.end_date, '9999-12-31')
          AND NEW.start_date <= COALESCE(a.end_date, '9999-12-31')
    );
END
"""


def _create_database_guards() -> None:
    dialect = op.get_context().dialect.name
    if dialect == "sqlite":
        for event in ("UPDATE", "DELETE"):
            op.execute(
                f"CREATE TRIGGER trg_audit_event_no_{event.lower()} BEFORE {event} ON audit_event "
                "BEGIN SELECT RAISE(ABORT, 'audit_event is append-only'); END"
            )
        op.execute(_SCHEDULE_OVERLAP_SQLITE.format(event="insert", event_sql="INSERT"))
        op.execute(
            _SCHEDULE_OVERLAP_SQLITE.format(
                event="update",
                event_sql="UPDATE OF start_date, end_date, status, availability_type, employee_id",
            )
        )
    elif dialect == "postgresql":
        op.execute(
            "CREATE OR REPLACE FUNCTION wfiq_reject_audit_change() RETURNS trigger "
            "LANGUAGE plpgsql AS $$ BEGIN "
            "RAISE EXCEPTION 'audit_event is append-only'; END; $$"
        )
        op.execute(
            "CREATE TRIGGER trg_audit_event_append_only BEFORE UPDATE OR DELETE ON audit_event "
            "FOR EACH ROW EXECUTE FUNCTION wfiq_reject_audit_change()"
        )
        op.execute(
            "CREATE TRIGGER trg_audit_event_no_truncate BEFORE TRUNCATE ON audit_event "
            "FOR EACH STATEMENT EXECUTE FUNCTION wfiq_reject_audit_change()"
        )
        op.execute("CREATE EXTENSION IF NOT EXISTS btree_gist")
        op.execute(
            "ALTER TABLE availability ADD CONSTRAINT ex_availability_schedule_no_overlap "
            "EXCLUDE USING gist (employee_id WITH =, daterange(start_date, end_date, '[]') WITH &&) "
            "WHERE (availability_type = 'WORK_SCHEDULE' AND status <> 'CANCELLED')"
        )
    else:  # pragma: no cover - only SQLite and PostgreSQL are supported
        raise NotImplementedError(f"unsupported dialect {dialect}")


def _drop_database_guards() -> None:
    dialect = op.get_context().dialect.name
    if dialect == "sqlite":
        for name in (
            "trg_audit_event_no_update",
            "trg_audit_event_no_delete",
            "trg_availability_schedule_no_overlap_insert",
            "trg_availability_schedule_no_overlap_update",
        ):
            op.execute(f"DROP TRIGGER IF EXISTS {name}")
