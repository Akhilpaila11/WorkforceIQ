"""Alembic migrations: up/down/up on a disposable database, no drift, PostgreSQL rendering."""

from __future__ import annotations

import io
import os
from pathlib import Path

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import inspect

from app.core.database import create_db_engine
from app.db.registry import metadata
from tests.conftest import alembic_config, sqlite_url

pytestmark = pytest.mark.integration


def test_single_linear_history(backend_dir: Path):
    script = ScriptDirectory.from_config(alembic_config("sqlite://"))
    heads = script.get_heads()
    assert heads == ["0001"]
    assert [r.revision for r in script.walk_revisions()] == ["0001"]


def test_upgrade_downgrade_upgrade(tmp_path: Path):
    url = sqlite_url(tmp_path / "cycle.sqlite3")
    cfg = alembic_config(url)
    engine = create_db_engine(url)

    command.upgrade(cfg, "head")
    tables = set(inspect(engine).get_table_names())
    assert set(metadata.tables) <= tables
    assert "alembic_version" in tables

    command.downgrade(cfg, "base")
    assert set(inspect(engine).get_table_names()) == {"alembic_version"}

    command.upgrade(cfg, "head")
    assert set(metadata.tables) <= set(inspect(engine).get_table_names())
    engine.dispose()


def test_models_and_migration_do_not_drift(migrated_template: Path):
    # Raises alembic.util.exc.AutogenerateDiffsDetected if the models differ from the DB.
    command.check(alembic_config(sqlite_url(migrated_template)))


def test_database_guards_exist_in_sqlite(migrated_template: Path):
    engine = create_db_engine(sqlite_url(migrated_template))
    with engine.connect() as conn:
        triggers = {
            row[0]
            for row in conn.exec_driver_sql("SELECT name FROM sqlite_master WHERE type='trigger'")
        }
    engine.dispose()
    assert triggers == {
        "trg_audit_event_no_update",
        "trg_audit_event_no_delete",
        "trg_availability_schedule_no_overlap_insert",
        "trg_availability_schedule_no_overlap_update",
    }


def test_postgresql_ddl_renders_offline():
    """Compiles the migration to PostgreSQL SQL without a server (live run: see below)."""
    buffer = io.StringIO()
    cfg = alembic_config("postgresql+psycopg://user@localhost/offline")
    cfg.output_buffer = buffer
    command.upgrade(cfg, "head", sql=True)
    sql = buffer.getvalue()
    for expected in (
        "CREATE TABLE employee",
        "JSONB",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY",
        "BOOLEAN DEFAULT true",
        "WHERE effective_to IS NULL",
        "EXCLUDE USING gist",
        "CREATE TRIGGER trg_audit_event_append_only",
        "ON DELETE RESTRICT",
    ):
        assert expected in sql, expected


